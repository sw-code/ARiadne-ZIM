import { useEffect } from "react";
import { useAssets } from "expo-asset";
import { ViroDetectedObject, ViroObjectDetector } from "@reactvision/react-viro";
import { Listener } from "@/src/shared/ReactExtensions";
import { log } from "@/src/shared/Logger";
import { useObjectDetectionSetting } from "@/src/3d/objectDetectionSetting";

export type DetectedObject = ViroDetectedObject;

// Inference competes with the Viro renderer for CPU and GPU, and rendering is already the bottleneck.
// Recognising landmarks for POI matching does not need more than a few frames per second.
const detectionsPerSecond = 2;

// Generated by scripts/export-detector-model.py, which also defines the detectable classes.
// Loaded through Metro instead of the native Android assets or iOS bundle,
// because those are wiped whenever the native directories are regenerated.
// eslint-disable-next-line @typescript-eslint/no-require-imports
const poiDetectorModel = require("@assets/models/poi-detector.onnx");

type DetectorProps = { onDetectionsChanged: Listener<DetectedObject[]> };

/// Detects POI-relevant objects in the camera feed of the ViroARSceneNavigator it is mounted next to,
/// if object detection is switched on in the Settings.
export function PoiObjectDetector({ onDetectionsChanged }: DetectorProps) {
  const [isObjectDetectionEnabled, , isSettingLoaded] = useObjectDetectionSetting();

  // marks each AR session in the log, so frame rates measured on test walks can be matched to the setting
  useEffect(() => {
    if (isSettingLoaded) log.info(`OBJECT DETECTION | ${isObjectDetectionEnabled ? "On" : "Off"}`);
  }, [isSettingLoaded, isObjectDetectionEnabled]);

  return isSettingLoaded && isObjectDetectionEnabled ? (
    <ObjectDetectorWithPoiModel onDetectionsChanged={onDetectionsChanged} />
  ) : null;
}

function ObjectDetectorWithPoiModel({ onDetectionsChanged }: DetectorProps) {
  const [modelAssets, modelError] = useAssets(poiDetectorModel);
  const modelUri = modelAssets?.[0]?.localUri;

  useEffect(() => {
    if (modelError) log.error("OBJECT DETECTION | Failed to load model", modelError);
  }, [modelError]);

  if (!modelUri) return null;

  return (
    <ViroObjectDetector
      style={{ position: "absolute", width: 0, height: 0 }}
      model={modelUri}
      maxFPS={detectionsPerSecond}
      onDetection={({ detections }) => onDetectionsChanged(detections)}
      onError={({ error }) => log.error("OBJECT DETECTION | Detector failed", error)}
    />
  );
}
